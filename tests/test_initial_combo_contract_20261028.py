@pytest.mark.parametrize("efficiency", [0.0, 0.9])
def test_helpers_follow_independent_continuous_slam_golden_sequence(efficiency):
    before, after = [], []
    current = 120.0
    for index in range(10):
        if index:
            current = ms.recover_initial_combo(current, 120., .2, 40.)
        before.append(current)
        current = ms.consume_combo(current, efficiency)
        after.append(current)
    assert before == GOLDEN[efficiency]["before"]
    assert after == GOLDEN[efficiency]["after"]


def _controlled_prepared_slam(efficiency):
    weapon = next(w for w in app.EXPORTS["weapons"] if w.get("nameEn") == "Fragor")
    scenario = Scenario(trigger_policy="emergent", combat_state={"meleeRoute": "slamContinuous"})
    effects = [ModEffect("WEAPON_MELEE_COMBO_INITIAL_BONUS", "ADD", 120.),
               ModEffect("WEAPON_MELEE_COMBO_USAGE_EFFICIENCY", "ADD", efficiency)]
    combat = prepare(dict(weapon=weapon, fire_mode=0, effects=effects, scenario=scenario), [], [])
    combat["melee"] = deepcopy(combat["melee"])
    original_resolve = combat["resolve"]

    def resolve(*args, **kwargs):
        stats, _ = original_resolve(*args, **kwargs)
        # One deterministic 100 damage body; actual Fragor slam attenuation is 3.
        # Suppress unrelated crit/proc randomness while exercising prepare/replay.
        return replace(stats, damage_types={"DT_IMPACT": 100.}, crit_chance=0.,
                       status_chance=0., multishot=1., slam_damage_ratio=1.), None

    combat["resolve"] = resolve
    combat["trigger_sources"] = []
    for segment in combat["melee"]["segments"]:
        if segment.get("hit"):
            segment["hit"]["extraProcs"] = []
    assert combat["melee"]["comboSpec"]["recoveryPerSecond"] == 40.
    stats, _ = resolve("selected", {}, 0.)
    return stats, combat


def _run_slam(efficiency, *, timeline):
    stats, combat = _controlled_prepared_slam(efficiency)
    target = dict(health=1e12, shield=0., armour=0., overguard=0., baseLevel=1,
                  healthType="", armourType="", shieldType="", damageController="custom")
    return combat_replay.replay(stats, target, attacks_per_second=stats.sustained_attack_rate,
                               window_seconds=2.01, combat=combat, trigger_sources=[],
                               headshot_chance=0., collect_timeline=timeline)


@pytest.mark.parametrize("efficiency", [0.0, 0.9])
def test_python_prepared_replay_matches_literal_combo_and_damage(efficiency, monkeypatch):
    monkeypatch.setattr(native_replay, "ENABLED", False)
    result = _run_slam(efficiency, timeline=True)
    events = result["melee"]["events"]
    golden = GOLDEN[efficiency]
    assert len(events) == 10
    assert [e["time"] for e in events] == pytest.approx([.2, .4, .6, .8, 1., 1.2, 1.4, 1.6, 1.8, 2.])
    assert [e["comboBefore"] for e in events] == golden["before"]
    assert [e["combo"] for e in events] == golden["after"]
    assert [e["comboRegenerated"] for e in events] == golden["regenerated"]
    assert [e["heavyMultiplier"] for e in events] == golden["multiplier"]
    assert result["totalWindowDamage"] == pytest.approx(golden["damage"])


@pytest.mark.parametrize("efficiency", [0.0, 0.9])
def test_native_prepared_replay_matches_literal_damage_without_fallback(efficiency, monkeypatch):
    if not getattr(native_replay.wfcore, "MELEE_INITIAL_COMBO_RECOVERY", 0):
        pytest.skip("native core lacks initial combo recovery feature")
    monkeypatch.setattr(native_replay, "ENABLED", True)
    native_before = native_replay.STATS["native"]
    result = _run_slam(efficiency, timeline=False)
    assert native_replay.STATS["native"] > native_before
    assert result["totalWindowDamage"] == pytest.approx(GOLDEN[efficiency]["damage"])


def test_initial_recovery_credits_the_interval_before_a_dynamic_buff_expires(monkeypatch):
    """A finite initial-combo buff expires between two fixed-cadence impacts.

    The first impact at .2 consumes all 120. The buff remains until .3,
    restoring exactly four points; lowering initial to zero does not erase
    those four. The next impact at .4 must read four, not retroactively zero.
    """
    monkeypatch.setattr(native_replay, "ENABLED", False)
    stats, combat = _controlled_prepared_slam(0.)
    original_resolve = combat["resolve"]

    def resolve(form, stacks, live_types, *args):
        part, radial = original_resolve(form, stacks, live_types, *args)
        return replace(part, initial_combo=120. if stacks.get("initial-buff", 0.) else 0.), radial

    combat["resolve"] = resolve
    source = dict(id="initial-buff", label="Finite initial combo", kind="unused", initialStacks=1.,
                  initialDuration=.3, duration=.3, maxStacks=1., perEvent=0., decay="reset")
    target = dict(health=1e12, shield=0., armour=0., overguard=0., baseLevel=1,
                  healthType="", armourType="", shieldType="", damageController="custom")
    result = combat_replay.replay(stats, target, attacks_per_second=stats.sustained_attack_rate,
                                 window_seconds=.41, combat=combat, trigger_sources=[source],
                                 headshot_chance=0., collect_timeline=True)
    assert [e["comboBefore"] for e in result["melee"]["events"]] == [120., 4.]


