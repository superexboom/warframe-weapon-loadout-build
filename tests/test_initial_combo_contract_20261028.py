def _run_dynamic_initial(*, rises, expires, timeline, time_step):
    stats, combat = _controlled_prepared_slam(0.)
    original_resolve = combat["resolve"]

    def resolve(form, stacks, live_types, *args):
        part, radial = original_resolve(form, stacks, live_types, *args)
        buff_on = bool(stacks.get("initial-switch", 0.))
        initial = 120. if buff_on != rises else 0.
        return replace(part, initial_combo=initial), radial

    combat["resolve"] = resolve
    # An explicit laboratory recovery pause: impacts at .2 and 1.0 seconds.
    # It isolates initial changes from the requested regular .2 s cadence.
    combat["melee"]["segments"][1]["fixed"] = .6
    source = dict(id="initial-switch", label="Initial combo switch", kind="unused",
                  initialStacks=1., initialDuration=expires, duration=expires,
                  maxStacks=1., perEvent=0., decay="reset")
    target = dict(health=1e12, shield=0., armour=0., overguard=0., baseLevel=1,
                  healthType="", armourType="", shieldType="", damageController="custom")
    return combat_replay.replay(stats, target, attacks_per_second=stats.sustained_attack_rate,
                               window_seconds=1.01, combat=combat, trigger_sources=[source],
                               headshot_chance=0., collect_timeline=timeline, time_step=time_step)


@pytest.mark.parametrize("time_step", [.01, .07, .25, 1.])
@pytest.mark.parametrize("native", [False, True])
@pytest.mark.parametrize("rises,before,multiplier,damage", [
    # Down: .2->.75 earns22, kept after initial falls; next impact has2x.
    (False, [120., 22.], [7., 2.], 2700.),
    # Up: .75->1.0 earns10. Do not credit .2->.75 under the new initial.
    (True, [0., 10.], [1., 1.], 600.),
])
def test_dynamic_initial_boundaries_preserve_literal_damage_in_both_cores(
        time_step, native, rises, before, multiplier, damage, monkeypatch):
    if native and not getattr(native_replay.wfcore, "MELEE_INITIAL_COMBO_RECOVERY", 0):
        pytest.skip("native core lacks initial combo recovery feature")
    monkeypatch.setattr(native_replay, "ENABLED", native)
    native_before = native_replay.STATS["native"]
    result = _run_dynamic_initial(rises=rises, expires=.75,
                                  timeline=not native, time_step=time_step)
    assert result["totalWindowDamage"] == pytest.approx(damage)
    assert result["shots"] == 2
    if native:
        assert native_replay.STATS["native"] > native_before
    else:
        events = result["melee"]["events"]
        assert [e["comboBefore"] for e in events] == before
        assert [e["heavyMultiplier"] for e in events] == multiplier


