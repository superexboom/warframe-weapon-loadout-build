def test_controlled_slam_helper_does_not_mutate_the_cached_schedule():
    weapon = next(w for w in app.EXPORTS["weapons"] if w.get("nameEn") == "Fragor")
    cached = ms.build_schedule(weapon, "slamContinuous")
    snapshot = deepcopy(cached)
    _, combat = _controlled_prepared_slam(0.)
    assert combat["melee"] is not cached
    combat["melee"]["segments"][0]["hit"]["extraProcs"].append("sentinel")
    combat["melee"]["segments"][1]["fixed"] = .6
    assert cached == snapshot


